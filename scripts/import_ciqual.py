"""Ciqual (ANSES) xlsx -> a SQL migration (public foods, upsert on source_ref = alim_code).

    python -I scripts/import_ciqual.py "Table Ciqual 2025_FR_2025_11_03.xlsx" supabase/migrations/<timestamp>_ciqual_<year>.sql

Ships as a migration so `supabase db push` loads it in production; re-running is safe (upsert on alim_code).
    python -I scripts/import_ciqual.py --selftest

Source: https://ciqual.anses.fr/#/cms/telechargement/node/20 (Licence Ouverte / Open Licence).
Required citation, shown in the app: "Anses. 2025. Table de composition nutritionnelle des aliments Ciqual."
Standard library only: an .xlsx is a zip of XML sheets.
"""
import re
import sys
import zipfile
import xml.etree.ElementTree as ET

NS = {'m': 'http://schemas.openxmlformats.org/spreadsheetml/2006/main'}
COLS = {  # our column -> regex on the Ciqual header (headers carry units and regulation names)
    'code': r'^alim_code$',
    'name': r'^alim_nom_fr$',
    'kcal_100g': r'^Energie, R.glement UE N. 1169[/ ]2011 \(kcal[/ ]100 ?g\)',
    'carbs_100g': r'^Glucides \(g[/ ]100 ?g\)',
    'protein_100g': r'^Prot.ines, N x facteur de Jones \(g[/ ]100 ?g\)',
    'fat_100g': r'^Lipides \(g[/ ]100 ?g\)',
    'sugar_100g': r'^Sucres \(g[/ ]100 ?g\)',
    'fiber_100g': r'^Fibres alimentaires \(g[/ ]100 ?g\)',
    'salt_100g': r'^Sel chlorure de sodium \(g[/ ]100 ?g\)',
}
REQUIRED = ('kcal_100g', 'carbs_100g', 'protein_100g', 'fat_100g')


def value(s):
    """Ciqual cell -> float or None. '-' = not measured, 'traces' = ~0, '< 0,5' = below the limit -> 0."""
    s = (s or '').strip().replace(',', '.')
    if s in ('', '-'):
        return None
    if s.lower() == 'traces' or s.startswith('<'):
        return 0.0
    try:
        return float(s)
    except ValueError:
        return None


def rows(path):
    z = zipfile.ZipFile(path)
    shared = []
    if 'xl/sharedStrings.xml' in z.namelist():
        for si in ET.fromstring(z.read('xl/sharedStrings.xml')).findall('m:si', NS):
            shared.append(''.join(t.text or '' for t in si.iter(f"{{{NS['m']}}}t")))
    sheet = ET.fromstring(z.read('xl/worksheets/sheet1.xml'))
    for r in sheet.find('m:sheetData', NS).findall('m:row', NS):
        out = {}
        for c in r.findall('m:c', NS):
            col = re.match(r'[A-Z]+', c.get('r')).group()
            v = c.find('m:v', NS)
            if c.get('t') == 's' and v is not None:
                out[col] = shared[int(v.text)]
            elif c.get('t') == 'inlineStr':
                out[col] = ''.join(t.text or '' for t in c.iter(f"{{{NS['m']}}}t"))
            else:
                out[col] = v.text if v is not None else ''
        yield out


def foods(path):
    it = rows(path)
    header = next(it)
    where = {}
    for key, rx in COLS.items():
        hit = [col for col, h in header.items() if re.search(rx, ' '.join(h.split()))]  # headers wrap with 

        if not hit:
            raise SystemExit(f'column not found for {key}: /{rx}/ - did the Ciqual layout change?')
        where[key] = hit[0]
    skipped = 0
    for r in it:
        f = {k: (r.get(col, '').strip() if k in ('code', 'name') else value(r.get(col))) for k, col in where.items()}
        if not f['code'] or not f['name'] or '(aliment moyen)' in f['name'] or any(f[k] is None for k in REQUIRED) \
                or not (0 <= f['kcal_100g'] <= 900) or any(not 0 <= f[k] <= 100 for k in REQUIRED[1:]):
            skipped += 1
            continue
        yield f
    print(f'skipped {skipped} rows (averaged foods, or energy/macros missing)', file=sys.stderr)


def sql_str(s):
    return "'" + s.replace("'", "''") + "'"


def sql_num(x):
    return 'null' if x is None else repr(round(x, 2))


def to_sql(items):
    out = ['-- Generated by scripts/import_ciqual.py from the ANSES Ciqual table (Licence Ouverte).',
           '-- Source: Anses. 2025. Table de composition nutritionnelle des aliments Ciqual.',
           'insert into foods (source, source_ref, name, kcal_100g, carbs_100g, protein_100g, fat_100g, sugar_100g, fiber_100g, salt_100g) values']
    vals = [f"  ('ciqual', {sql_str(f['code'])}, {sql_str(f['name'][:200])}, {sql_num(f['kcal_100g'])}, {sql_num(f['carbs_100g'])}, "
            f"{sql_num(f['protein_100g'])}, {sql_num(f['fat_100g'])}, {sql_num(f['sugar_100g'])}, {sql_num(f['fiber_100g'])}, {sql_num(f['salt_100g'])})"
            for f in items]
    if not vals:
        raise SystemExit('no rows: refusing to write an empty import')
    out.append(',\n'.join(vals))
    out.append('on conflict (source, source_ref) where source_ref is not null do update set name = excluded.name,\n'
               '  kcal_100g = excluded.kcal_100g, carbs_100g = excluded.carbs_100g, protein_100g = excluded.protein_100g,\n'
               '  fat_100g = excluded.fat_100g, sugar_100g = excluded.sugar_100g, fiber_100g = excluded.fiber_100g, salt_100g = excluded.salt_100g;')
    return '\n'.join(out) + '\n', len(vals)


def selftest():
    assert value('12,5') == 12.5 and value('-') is None and value('') is None
    assert value('traces') == 0 and value('< 0,5') == 0 and value('abc') is None
    sql, n = to_sql([{'code': '1', 'name': "Pain d'épice", 'kcal_100g': 350.0, 'carbs_100g': 70.0, 'protein_100g': 4.0,
                      'fat_100g': 3.0, 'sugar_100g': None, 'fiber_100g': 2.0, 'salt_100g': 0.5}])
    assert n == 1 and "'Pain d''épice'" in sql and 'null' in sql
    print('selftest ok')


if __name__ == '__main__':
    if sys.argv[1:] == ['--selftest']:
        selftest()
    else:
        src, dst = sys.argv[1:3]
        sql, n = to_sql(foods(src))
        open(dst, 'w', encoding='utf-8').write(sql)
        print(f'{n} foods -> {dst}')
